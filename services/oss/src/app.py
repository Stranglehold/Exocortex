@app.route('/admin/quick_promote', methods=['POST'])
@require_analyst_auth
def admin_quick_promote():
    """Quick-promote a staged claim using its own staging_confidence. No weights required."""
    data = request.get_json(force=True)
    claim_id = data.get('claim_id')
    if not claim_id:
        return jsonify({'ok': False, 'error': 'claim_id required'}), 400
    try:
        with get_conn() as conn:
            cur = conn.cursor()
            cur.execute("SELECT id, staging_confidence, source_id, trust_level FROM claims WHERE id=%s",
                        (int(claim_id),))
            row = cur.fetchone()
            if not row:
                return jsonify({'ok': False, 'error': 'claim not found'}), 404
            _, conf, src_id, trust = row
            if trust != 'STAGED':
                return jsonify({'ok': False, 'error': f'claim is {trust}, not STAGED'}), 400
            conf = float(conf or 0.7)
            cur.execute("SELECT name, confidence_score FROM sources WHERE id=%s", (src_id,))
            src = cur.fetchone()
            src_weights = json.dumps({(src[0] if src else 'unknown'): float(src[1] if src and src[1] else 0.7)})
            cur.execute("""
                INSERT INTO promotion_snapshots
                  (claim_id, promoted_at, promotion_confidence, source_weights,
                   threshold_at_promotion, promoting_evidence, falsification_predictions)
                VALUES (%s, NOW(), %s, %s, 0.5, '[]', '[]')
            """, (int(claim_id), conf, src_weights))
            cur.execute("UPDATE claims SET trust_level='PROMOTED' WHERE id=%s", (int(claim_id),))
            conn.commit()
        return jsonify({'ok': True, 'claim_id': int(claim_id)})
    except Exception as e:
        log.error(f"quick_promote: {e}")
        return jsonify({'ok': False, 'error': str(e)}), 500


@app.route('/admin/bulk_promote', methods=['POST'])
@require_analyst_auth
def admin_bulk_promote():
    """
    Bulk-promote STAGED claims whose staging_confidence >= threshold.

    Input:
        min_confidence:  float  0.0–1.0, default 0.7
        topic:           str    optional — filter to one topic tag
        dry_run:         bool   optional — count candidates without promoting
        analyst_token:   str    required

    Output:
        { ok, promoted, skipped, dry_run, topic, min_confidence }
    """
    data = request.get_json(force=True, silent=True) or {}
    min_conf = float(data.get('min_confidence', 0.7))
    min_conf = max(0.0, min(1.0, min_conf))
    topic_filter = data.get('topic')
    dry_run = bool(data.get('dry_run', False))

    try:
        with get_conn() as conn:
            cur = conn.cursor()

            # Collect candidate claim IDs.
            # staging_confidence is 0 for all STAGED claims (set at promotion time only).
            # Filter by source confidence_score instead.
            # Topic filter: staged claims lack topic_tags; join through source_topic_signals.
            if topic_filter:
                cur.execute(
                    """
                    SELECT DISTINCT c.id, COALESCE(s.confidence_score, 0.7), c.source_id
                    FROM claims c
                    LEFT JOIN sources s           ON s.id = c.source_id
                    JOIN source_topic_signals sts ON sts.source_id = c.source_id
                    WHERE c.trust_level = 'STAGED'
                      AND sts.topic = %s
                      AND COALESCE(s.confidence_score, 0.7) >= %s
                    ORDER BY c.id
                    """,
                    (topic_filter, min_conf),
                )
            else:
                cur.execute(
                    """
                    SELECT c.id, COALESCE(s.confidence_score, 0.7), c.source_id
                    FROM claims c
                    LEFT JOIN sources s ON s.id = c.source_id
                    WHERE c.trust_level = 'STAGED'
                      AND COALESCE(s.confidence_score, 0.7) >= %s
                    ORDER BY c.id
                    """,
                    (min_conf,),
                )
            candidates = cur.fetchall()

            if dry_run:
                return jsonify({
                    'ok':             True,
                    'dry_run':        True,
                    'would_promote':  len(candidates),
                    'topic':          topic_filter,
                    'min_confidence': min_conf,
                })

            promoted = 0
            skipped = 0
            for row in candidates:
                claim_id, src_conf_score, src_id = row[0], float(row[1] or 0.7), row[2]
                conf = src_conf_score if src_conf_score > 0 else 0.7
                try:
                    cur.execute("SELECT name, confidence_score FROM sources WHERE id=%s", (src_id,))
                    src = cur.fetchone()
                    src_name = src[0] if src else 'unknown'
                    src_conf = float(src[1] if src and src[1] else 0.7)
                    src_weights = json.dumps({src_name: src_conf})

                    cur.execute(
                        """
                        INSERT INTO promotion_snapshots
                          (claim_id, promoted_at, promotion_confidence, source_weights,
                           threshold_at_promotion, promoting_evidence, falsification_predictions)
                        VALUES (%s, NOW(), %s, %s, %s, '[]', '[]')
                        """,
                        (claim_id, conf, src_weights, min_conf),
                    )
                    cur.execute(
                        "UPDATE claims SET trust_level='PROMOTED' WHERE id=%s",
                        (claim_id,),
                    )
                    promoted += 1
                except Exception as row_err:
                    log.warning(f"[BULK-PROMOTE] Skipped claim {claim_id}: {row_err}")
                    skipped += 1

            conn.commit()

        log.info(
            f"[BULK-PROMOTE] promoted={promoted} skipped={skipped} "
            f"threshold={min_conf} topic={topic_filter or 'all'}"
        )
        return jsonify({
            'ok':             True,
            'promoted':       promoted,
            'skipped':        skipped,
            'dry_run':        False,
            'topic':          topic_filter,
            'min_confidence': min_conf,
        })

    except Exception as e:
        log.error(f"bulk_promote: {e}")
        return jsonify({'ok': False, 'error': str(e)}), 500


