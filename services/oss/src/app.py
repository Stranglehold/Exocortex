def _swarmfish_request(path: str, method: str = "GET", body: dict = None) -> dict:
    """
    Make an authenticated request to SWARMFISH and return parsed JSON.

    Routing:
    - /acp/outcome → V2 Agent Zero plugin endpoint if SWARMFISH_V2_URL is set,
      translating V1 {session_id, outcome: str, was_correct: bool} to
      V2 {session_id, outcome: float 0.0-1.0, notes: str}.
    - All other paths (monitor status/toggle/run_now) → V1 base URL (dead in V2).
    """
    # V2 calibration routing for /acp/outcome
    if path == "/acp/outcome" and SWARMFISH_V2_URL and body:
        v2_body = {
            "session_id": body.get("session_id"),
            "outcome":    1.0 if body.get("was_correct") else 0.0,
            "notes":      str(body.get("outcome", ""))[:500],
        }
        v2_path = "/api/plugins/swarmfish/api_swarmfish_outcome"
        url     = f"{SWARMFISH_V2_URL}{v2_path}"
        encoded = json.dumps(v2_body).encode()
        headers = {
            "Content-Type": "application/json",
            "X-API-KEY":    SWARMFISH_V2_API_KEY,
        }
        req = urllib.request.Request(url, data=encoded, method="POST", headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=5) as resp:
                return json.loads(resp.read().decode())
        except urllib.error.HTTPError as e:
            body_text = e.read().decode()
            try:
                return json.loads(body_text)
            except Exception:
                raise RuntimeError(f"HTTP {e.code}: {body_text[:200]}")

    url = f"{SWARMFISH_BASE_URL}{path}"
    encoded = json.dumps(body).encode() if body is not None else None
    headers = {"X-Analyst-Token": SWARMFISH_ANALYST_TOKEN}
    if encoded is not None:
        headers["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=encoded, method=method, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=5) as resp:
            return json.loads(resp.read().decode())
    except urllib.error.HTTPError as e:
        body_text = e.read().decode()
        try:
            return json.loads(body_text)
        except Exception:
            raise RuntimeError(f"HTTP {e.code}: {body_text[:200]}")


